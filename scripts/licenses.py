"""Write docs/SBOM.md from the installed environment and fail on licenses Lyst's core may not ship.

    uv run python scripts/licenses.py          # writes docs/SBOM.md, exits 1 on a disallowed license
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

# Lyst is AGPL-3.0-only. A dependency must be open source and compatible with AGPLv3: permissive (MIT,
# BSD, Apache-2.0, PSF, ISC, Zlib), weak copyleft (MPL-2.0, LGPL-3.0) or GPLv3/AGPLv3. Refused: licenses that
# are not open source (SSPL, BUSL, Commons Clause, Elastic, proprietary) and GPL-2.0-only, which cannot be
# combined with AGPLv3.
DENY = ("SSPL", "BUSL", "Business Source", "Commons Clause", "Elastic License", "Proprietary",
        "GPL-2.0-only", "GPLv2 only")
ALLOW_EXCEPTIONS: set[str] = set()
DEV_ONLY = {"pytest", "ruff", "pip-licenses", "iniconfig", "pluggy", "Pygments", "prettytable", "wcwidth",
            "tomli"}

out = subprocess.run([sys.executable, "-m", "piplicenses", "--format=json", "--with-urls"],
                     capture_output=True, text=True, check=True)
rows = sorted(json.loads(out.stdout), key=lambda r: r["Name"].lower())
bad = [r for r in rows if r["Name"] != "lyst" and any(d.lower() in r["License"].lower() for d in DENY)
       and not any(e in r["License"] for e in ALLOW_EXCEPTIONS)]
lines = ["# Software bill of materials", "",
         "Generated by `scripts/licenses.py` from the locked environment (`uv.lock`). Lyst is licensed "
         "AGPL-3.0-only. Every dependency below is open source and compatible with AGPLv3: all are permissive "
         "(MIT, BSD, Apache-2.0, PSF, MIT-CMU) except certifi (MPL-2.0, weak copyleft, used unmodified), which "
         "MPL-2.0 section 3.3 allows in a larger GPL-family work. The check fails on licenses that are not open "
         "source (SSPL, BUSL, Commons Clause, Elastic, proprietary) and on GPL-2.0-only.", "",
         "| Package | Version | License | Scope | Source |", "|---|---|---|---|---|"]
for r in rows:
    if r["Name"] == "lyst":
        continue
    scope = "dev" if r["Name"] in DEV_ONLY else "runtime"
    lines.append(f"| {r['Name']} | {r['Version']} | {r['License']} | {scope} | {r['URL']} |")
Path("docs/SBOM.md").write_text("\n".join(lines) + "\n")
if bad:
    print("Disallowed licenses:", ", ".join(f"{r['Name']} ({r['License']})" for r in bad))
    sys.exit(1)
print(f"{len(rows) - 1} packages, all allowed. Wrote docs/SBOM.md")
