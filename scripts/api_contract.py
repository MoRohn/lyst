"""The HTTP API's compatibility record: one line per operation with what a caller must send.

    uv run python scripts/api_contract.py           # print the current contract
    uv run python scripts/api_contract.py --write   # record it in docs/api/contract.txt
    uv run python scripts/api_contract.py --check   # exit 1 on a breaking change against the record

Breaking: an operation removed, or a new required query parameter or body field on an existing operation.
Additions (new operations, optional fields) are compatible; ``--write`` records them. tests/test_api_contract.py
runs the check, so a breaking change cannot land without bumping Lyst-API-Version and the record together.
"""

from __future__ import annotations

import sys
from pathlib import Path

RECORD = Path(__file__).resolve().parents[1] / "docs" / "api" / "contract.txt"
HEADER = "# Lyst HTTP API contract (generated by scripts/api_contract.py; one line per operation)\n"


def _resolve(spec: dict, schema: dict) -> dict:
    while "$ref" in schema:
        schema = spec["components"]["schemas"][schema["$ref"].rsplit("/", 1)[-1]]
    return schema


def operations(spec: dict | None = None) -> dict[str, dict[str, list[str]]]:
    if spec is None:
        from lyst.api import create_app  # noqa: PLC0415

        spec = create_app(None, start_workers=False).openapi()
    ops: dict[str, dict[str, list[str]]] = {}
    for path, methods in spec["paths"].items():
        for method, op in methods.items():
            if method not in ("get", "post", "put", "patch", "delete"):
                continue
            query = sorted(p["name"] for p in op.get("parameters", []) if p.get("in") == "query" and p.get("required"))
            body: list[str] = []
            content = (op.get("requestBody") or {}).get("content", {})
            for media in content.values():
                schema = _resolve(spec, media.get("schema", {}))
                body = sorted(schema.get("required", []))
                break
            ops[f"{method.upper()} {path}"] = {"query": query, "body": body}
    return ops


def render(ops: dict[str, dict[str, list[str]]]) -> str:
    lines = [HEADER]
    for key in sorted(ops):
        o = ops[key]
        lines.append(f"{key} | query: {','.join(o['query']) or '-'} | body: {','.join(o['body']) or '-'}\n")
    return "".join(lines)


def parse(text: str) -> dict[str, dict[str, list[str]]]:
    ops = {}
    for line in text.splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        key, q, b = (s.strip() for s in line.split("|"))
        split = lambda s: [] if s.split(":", 1)[1].strip() == "-" else s.split(":", 1)[1].strip().split(",")  # noqa: E731
        ops[key] = {"query": split(q), "body": split(b)}
    return ops


def breaking(recorded: dict, current: dict) -> list[str]:
    out = []
    for key, was in recorded.items():
        now = current.get(key)
        if now is None:
            out.append(f"{key}: removed")
            continue
        for part in ("query", "body"):
            added = sorted(set(now[part]) - set(was[part]))
            if added:
                out.append(f"{key}: new required {part} {', '.join(added)}")
    return out


def main(argv: list[str]) -> int:
    current = operations()
    if "--write" in argv:
        RECORD.parent.mkdir(parents=True, exist_ok=True)
        RECORD.write_text(render(current))
        print(f"recorded {len(current)} operations in {RECORD}")
        return 0
    if "--check" in argv:
        problems = breaking(parse(RECORD.read_text()), current)
        for p in problems:
            print("BREAKING", p)
        new = sorted(set(current) - set(parse(RECORD.read_text())))
        for n in new:
            print("new (compatible, not yet recorded):", n)
        return 1 if problems else 0
    sys.stdout.write(render(current))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
