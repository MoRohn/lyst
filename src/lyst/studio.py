"""The Analytical Engineering Studio: from a sentence to a maintained reporting dashboard.

"Create an automated operating margin reporting dashboard by region, refreshed weekly" becomes:

1. **Design**: the governed metrics named in the request, the dimension, the grain, the period range.
2. **Verified SQL**: every query is the semantic layer's compiled SQL run through the guard; the design
   stores the queries and their row counts.
3. **Extracts**: each query's rows are written as Parquet beside the app. The generated app reads only
   those extracts, never a database (Acumane's arch-runtime rule), so it can run anywhere.
4. **The app**: a standalone Streamlit script generated from a template: KPI tiles for the latest period
   with change against the prior one, a trend per metric, a breakdown by the dimension, a table, and the
   data checks in the footer. ``README.md`` documents every metric's definition and version.
5. **Checks**: data-quality on the sources, a syntax check on the app, and a headless render with
   Streamlit's ``AppTest``: a dashboard that raises is not published.
6. **Refresh**: a schedule (approval required) whose task re-runs the same queries, rewrites the extracts,
   re-runs the checks and re-renders; the refresh count and last refresh time live on the dashboard.
7. **Monitoring**: the dashboard's manifest records the checks; a failing refresh leaves the previous
   extracts in place and marks the dashboard ``stale``.
"""

