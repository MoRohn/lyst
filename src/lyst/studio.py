APP_TEMPLATE = '''# Generated by Lyst's Studio. Reads the extracts beside this file only; refresh them with Lyst.
import json
from pathlib import Path

import pandas as pd
import plotly.graph_objects as go
import streamlit as st

HERE = Path(__file__).parent
M = json.loads((HERE / "manifest.json").read_text())
st.set_page_config(page_title=M["title"], layout="wide")
st.title(M["title"])
st.caption(f"Refreshed {M['refreshed_at'][:16]} · data through {M['data_through']} · {len(M['metrics'])} governed metrics")


def fmt(v, f):
    if v is None or pd.isna(v):
        return "n/a"
    if f == "percent":
        return f"{v * 100:.1f}%"
    if f == "currency":
        return f"${v / 1e6:.2f}M" if abs(v) >= 1e6 else f"${v:,.0f}"
    return f"{v:,.0f}"


tiles = st.columns(len(M["metrics"]))
for col, m in zip(tiles, M["metrics"]):
    s = pd.read_parquet(HERE / m["series_file"]).sort_values("period")
    latest, prior = s.iloc[-1], (s.iloc[-2] if len(s) > 1 else None)
    delta = None
    if prior is not None and pd.notna(prior["value"]) and pd.notna(latest["value"]):
        delta = latest["value"] - prior["value"]
        delta = f"{delta * 100:+.1f} pts" if m["format"] == "percent" else fmt(delta, m["format"])
    col.metric(m["title"], fmt(latest["value"], m["format"]), delta, delta_color="normal" if m["higher_is_better"] else "inverse")

for m in M["metrics"]:
    st.subheader(m["title"])
    st.caption(m["description"])
    s = pd.read_parquet(HERE / m["series_file"]).sort_values("period")
    b = pd.read_parquet(HERE / m["breakdown_file"])
    c1, c2 = st.columns([3, 2])
    fig = go.Figure(go.Scatter(x=s["period"], y=s["value"], mode="lines+markers", marker={"size": 4}))
    fig.update_layout(height=280, margin={"l": 8, "r": 8, "t": 8, "b": 8},
                      yaxis={"tickformat": ".0%"} if m["format"] == "percent" else {})
    c1.plotly_chart(fig, width="stretch", config={"displayModeBar": False})
    latest_period = b["period"].max()
    lb = b[b["period"] == latest_period].sort_values("value", ascending=False)
    fig2 = go.Figure(go.Bar(x=lb[M["dimension"]], y=lb["value"]))
    fig2.update_layout(height=280, margin={"l": 8, "r": 8, "t": 8, "b": 8},
                       yaxis={"tickformat": ".0%"} if m["format"] == "percent" else {})
    c2.plotly_chart(fig2, width="stretch", config={"displayModeBar": False})
    with st.expander("Data"):
        st.dataframe(b.pivot_table(index="period", columns=M["dimension"], values="value").sort_index(ascending=False),
                     width="stretch")

with st.expander("Definitions and checks"):
    for m in M["metrics"]:
        st.markdown(f"**{m['title']}** (v{m['version']}): {m['description']}")
        st.code(m["sql"], language="sql")
    for c in M["checks"]:
        st.write(("✓" if c["passed"] else "✕") + " " + c["name"] + ": " + c["detail"])
'''

REQUEST = re.compile(r"\b(create|build|set up|make|generate)\b.*\b(dashboard|report(ing)?( system)?|scorecard)\b", re.I)
REFRESH = re.compile(r"\b(refresh(ed)?|updated?)\s+(every\s+)?(daily|weekly|monthly|hourly|each (day|week|month))\b", re.I)
INTERVALS = {"hourly": 3600, "daily": 86400, "weekly": 7 * 86400, "monthly": 30 * 86400,
             "each day": 86400, "each week": 7 * 86400, "each month": 30 * 86400}


def wants_dashboard(text: str) -> bool:
    return bool(REQUEST.search(text))


def refresh_interval(text: str) -> int | None:
    m = REFRESH.search(text)
    if not m:
        return None
    return INTERVALS.get(m.group(4).lower())


class StudioService:
    def __init__(self, stores: Stores, guard: Guard, data, semantic, runtime, home: Path, knowledge=None):
        self.stores, self.guard, self.data, self.semantic, self.runtime, self.home, self.knowledge = \
            stores, guard, data, semantic, runtime, home, knowledge

    def _db(self, ws: str):
        return self.stores.workspace(ws)

    def _dir(self, ws: str, did: str) -> Path:
        return self.home / "dashboards" / ws / did

    # -- design -----------------------------------------------------------------------------

    def design(self, actor: Principal, ws: str, metrics: list[str], *, dimension: str | None, title: str | None,
               grain: str = "month", every_seconds: int | None, target: str = "dash",
               narrative: dict[str, Any] | None = None) -> dict[str, Any]:
        self.guard.require(actor, ws, "data.read")
        if target not in ("dash", "streamlit"):
            raise ValueError("target must be dash or streamlit")
        specs = [self.semantic.get(actor, ws, m) for m in metrics]
        dims = set(specs[0].dimensions)
        for sp in specs[1:]:
            dims &= set(sp.dimensions)
        dim = dimension if dimension in dims else (sorted(dims)[0] if dims else None)
        if not dim:
            raise ValueError("the metrics share no dimension to break down by")
        catalog = {d["name"]: d for d in self.data.catalog(actor, ws)}
        design = {"title": title or f"{' & '.join(sp.title for sp in specs)} by {dim}", "grain": grain, "dimension": dim,
                  "every_seconds": every_seconds, "target": target, "narrative": narrative or {}, "metrics": []}
        from .analyst.engine import _sum_target  # noqa: PLC0415
        from .onboarding import fiscal_start  # noqa: PLC0415 - quarterly dashboards follow the fiscal calendar
        from .semantic import _cond  # noqa: PLC0415

        fs = fiscal_start(self._db(ws))
        for sp in specs:
            series_sql = compile_metric(sp, grain=grain, fiscal_start=fs)
            breakdown_sql = compile_metric(sp, grain=grain, by=[dim], fiscal_start=fs)
            r1 = self.data.query(actor, ws, series_sql)
            r2 = self.data.query(actor, ws, breakdown_sql)
            if sp.kind == "ratio":
                num, den = _sum_target(sp.numerator), _sum_target(sp.denominator)
            else:
                num, den = _sum_target(sp.measure), None
            if not num or (sp.kind == "ratio" and not den):
                raise ValueError(f"{sp.title} is not additive (sum or count, or a ratio of them); a dashboard needs additive parts "
                                 "so that filtering recomputes it exactly")
            where = " AND ".join([f'"{sp.time_column}" IS NOT NULL'] + [_cond(f) for f in sp.filters])
            parts_sql = (f'SELECT date_trunc(\'{grain}\', "{sp.time_column}") AS period, "{dim}" AS {dim}, SUM({num}) AS num, '
                         f'{"SUM(" + den + ")" if den else "NULL"} AS den FROM "{sp.dataset}" WHERE {where} GROUP BY 1, 2 ORDER BY 1, 2')
            design["metrics"].append({"name": sp.name, "title": sp.title, "description": sp.description, "format": sp.format,
                                      "higher_is_better": sp.higher_is_better, "dataset": sp.dataset, "kind": sp.kind,
                                      "dataset_version": catalog[sp.dataset]["version"],
                                      "version": self._db(ws).scalar("SELECT current_version FROM metrics WHERE name = ?", [sp.name]),
                                      "series_sql": series_sql, "breakdown_sql": breakdown_sql, "parts_sql": parts_sql,
                                      "series_rows": len(r1.rows), "breakdown_rows": len(r2.rows),
                                      "query_ids": [r1.query_id, r2.query_id]})
        return design

    # -- build ------------------------------------------------------------------------------

    def build(self, actor: Principal, ws: str, design: dict[str, Any], *, task_id: str | None = None) -> dict[str, Any]:
        self.guard.require(actor, ws, "data.ingest")  # building writes files and proposes a schedule: editor and above
        did = "db_" + (task_id[-8:] if task_id else uuid.uuid4().hex[:8])  # one dashboard per task: a resumed step finds it
        existing = self._db(ws).query("SELECT id, title, path, status, checks, schedule_id FROM dashboards WHERE id = ?", [did])
        if existing:
            e = existing[0]
            return {"dashboard_id": e["id"], "title": e["title"], "path": e["path"], "status": e["status"],
                    "checks": json.loads(e["checks"] or "[]"), "schedule": {"schedule_id": e["schedule_id"]} if e["schedule_id"] else None,
                    "target": design.get("target", "streamlit"),
                    "files": sorted(str(p.relative_to(e["path"])) for p in Path(e["path"]).rglob("*") if p.is_file()
                                    and ".cache" not in p.parts and "__pycache__" not in p.parts), "resumed": True}
        folder = self._dir(ws, did)
        folder.mkdir(parents=True, exist_ok=True)
        manifest = self._materialize(actor, ws, design, folder, task_id=task_id)
        checks = self._write_and_verify(folder, design, manifest)
        manifest["checks"] = checks
        (folder / "manifest.json").write_text(json.dumps(manifest, indent=1, default=str))
        status = "published" if all(c["passed"] for c in checks if c["severity"] == "error") else "failed"
        self._db(ws).execute(
            "INSERT INTO dashboards (id, title, design, path, status, created_by, last_refresh_at, refresh_count, checks) "
            "VALUES (?, ?, ?, ?, ?, ?, now(), 0, ?)",
            [did, design["title"], json.dumps(design), str(folder), status, actor.user_id, json.dumps(checks)])
        schedule = None
        if design.get("every_seconds") and status == "published":
            schedule = self.runtime.create_schedule(actor, ws, f"Refresh {design['title']}", f"refresh dashboard {did}",
                                                    design["every_seconds"])
            self._db(ws).execute("UPDATE dashboards SET schedule_id = ? WHERE id = ?", [schedule["schedule_id"], did])
        self.guard.audit(actor, ws, "dashboard.build", did, status, {"metrics": [m["name"] for m in design["metrics"]]})
        if self.knowledge:
            self.knowledge.upsert_entity(actor, ws, "artifact", did, description=design["title"], owner=actor.user_id,
                                         attributes={"kind": "dashboard"}, source="system")
            for m in design["metrics"]:
                self.knowledge.relate(actor, ws, "artifact", did, "reads", "metric", m["name"], source="system")
        reg = self.assets.on_dashboard(actor, ws, did, design, checks, task_id=task_id) if getattr(self, "assets", None) else None
        return {"dashboard_id": did, "asset": reg, "title": design["title"], "path": str(folder), "status": status, "checks": checks,
                "schedule": schedule, "target": design.get("target", "streamlit"),
                "files": sorted(str(p.relative_to(folder)) for p in folder.rglob("*") if p.is_file() and ".cache" not in p.parts
                                and "__pycache__" not in p.parts)}

    def _materialize(self, actor: Principal, ws: str, design: dict[str, Any], folder: Path, *, task_id: str | None) -> dict[str, Any]:
        metrics, data_through = [], None
        for m in design["metrics"]:
            s = self.data.query(actor, ws, m["series_sql"], task_id=task_id)
            b = self.data.query(actor, ws, m["breakdown_sql"], task_id=task_id)
            series_file, breakdown_file = f"{m['name']}_series.parquet", f"{m['name']}_by_{design['dimension']}.parquet"
            self._parquet(folder / series_file, s.columns, s.rows)
            self._parquet(folder / breakdown_file, b.columns, b.rows)
            last = max((str(r[0])[:10] for r in s.rows), default=None)
            data_through = max(filter(None, [data_through, last]), default=None)
            latest = next((float(r[1]) for r in sorted(s.rows, key=lambda r: str(r[0]), reverse=True) if r[1] is not None), None)
            entry = {**{k: m[k] for k in ("name", "title", "description", "format", "higher_is_better", "version", "dataset")},
                     "kind": m.get("kind", "simple"), "sql": m["series_sql"], "series_file": series_file, "breakdown_file": breakdown_file,
                     "rows": len(s.rows), "latest_value": latest, "sha256": hashlib.sha256((folder / series_file).read_bytes()).hexdigest()}
            if design.get("target", "streamlit") == "dash" and m.get("parts_sql"):
                (folder / "data").mkdir(exist_ok=True)
                pr = self.data.query(actor, ws, m["parts_sql"], task_id=task_id, max_rows=10_000)
                self._parquet(folder / "data" / f"parts_{m['name']}.parquet", pr.columns, pr.rows)
                entry["parts_file"] = f"data/parts_{m['name']}.parquet"
            metrics.append(entry)
        return {"id": folder.name, "title": design["title"], "dimension": design["dimension"], "grain": design["grain"],
                "target": design.get("target", "streamlit"),
                "metrics": metrics, "refreshed_at": datetime.now(UTC).isoformat(timespec="seconds"), "data_through": data_through,
                "checks": []}

    @staticmethod
    def _parquet(path: Path, columns: list[str], rows: list[list[Any]]) -> None:
        cols = {c: [r[i] for r in rows] for i, c in enumerate(columns)}
        if "period" in cols:
            cols["period"] = [str(v)[:10] for v in cols["period"]]
        pq.write_table(pa.table(cols), path)

    def _write_and_verify(self, folder: Path, design: dict[str, Any], manifest: dict[str, Any]) -> list[dict[str, Any]]:
        """App files for the target, the manifest (the render reads it), then the target's checks."""
        from . import studio_dash  # noqa: PLC0415

        (folder / "README.md").write_text(self._readme(design, manifest))
        (folder / "manifest.json").write_text(json.dumps(manifest, indent=1, default=str))
        if design.get("target", "streamlit") == "dash":
            studio_dash.write_app(folder, design, manifest)
            checks = studio_dash.verify(folder)
            for m in manifest["metrics"]:
                checks.append({"name": f"extract:{m['name']}", "passed": m["rows"] > 0, "detail": f"{m['rows']} rows, sha256 {m['sha256'][:12]}",
                               "severity": "error"})
            return checks
        (folder / "app.py").write_text(APP_TEMPLATE)
        return self._verify(folder, manifest)

    def _verify(self, folder: Path, manifest: dict[str, Any]) -> list[dict[str, Any]]:
        checks = []
        try:
            compile((folder / "app.py").read_text(), str(folder / "app.py"), "exec")
            checks.append({"name": "app_syntax", "passed": True, "detail": "app.py compiles", "severity": "error"})
        except SyntaxError as exc:
            checks.append({"name": "app_syntax", "passed": False, "detail": str(exc), "severity": "error"})
        for m in manifest["metrics"]:
            ok = m["rows"] > 0
            checks.append({"name": f"extract:{m['name']}", "passed": ok, "detail": f"{m['rows']} rows, sha256 {m['sha256'][:12]}",
                           "severity": "error"})
        try:
            from streamlit.testing.v1 import AppTest  # noqa: PLC0415

            at = AppTest.from_file(str(folder / "app.py"), default_timeout=60)
            at.run()
            errs = [e.value for e in at.exception]
            checks.append({"name": "headless_render", "passed": not errs, "detail": "rendered without exceptions" if not errs
                           else "; ".join(str(e)[:200] for e in errs), "severity": "error"})
        except Exception as exc:  # noqa: BLE001
            checks.append({"name": "headless_render", "passed": False, "detail": f"{type(exc).__name__}: {exc}"[:300], "severity": "error"})
        return checks

    @staticmethod
    def _readme(design: dict[str, Any], manifest: dict[str, Any]) -> str:
        runner = "`pip install -r requirements.txt && python app.py` (Dash)" if design.get("target", "streamlit") == "dash" else "`streamlit run app.py`"
        lines = [f"# {design['title']}", "", f"Generated by Lyst. Run with {runner}; the app reads the Parquet "
                 "extracts beside it and nothing else. Refreshing is Lyst's job (an approved schedule re-runs the governed "
                 "queries, rewrites the extracts and re-checks the app).", "", f"Dimension: `{design['dimension']}` · grain: "
                 f"{design['grain']} · data through {manifest['data_through']}", "", "## Metrics", ""]
        for m in design["metrics"]:
            lines += [f"### {m['title']} (v{m['version']})", "", m["description"] or "", "", "```sql", m["series_sql"], "```", ""]
        return "\n".join(lines)

    # -- refresh ----------------------------------------------------------------------------

    def refresh(self, actor: Principal, ws: str, dashboard_id: str, *, task_id: str | None = None) -> dict[str, Any]:
        self.guard.require(actor, ws, "task.control", dashboard_id)
        row = self._db(ws).query("SELECT * FROM dashboards WHERE id = ?", [dashboard_id])
        if not row:
            raise KeyError(dashboard_id)
        d = row[0]
        if d["status"] == "retired":
            raise ValueError("this dashboard is retired; build a new one instead of refreshing it")
        design = json.loads(d["design"])
        folder = Path(d["path"])
        staging = folder.parent / (folder.name + ".staging")
        if staging.exists():
            shutil.rmtree(staging)
        staging.mkdir(parents=True)
        try:
            manifest = self._materialize(actor, ws, design, staging, task_id=task_id)
            checks = self._write_and_verify(staging, design, manifest)
            manifest["checks"] = checks
            (staging / "manifest.json").write_text(json.dumps(manifest, indent=1, default=str))
            ok = all(c["passed"] for c in checks if c["severity"] == "error")
        except Exception as exc:  # noqa: BLE001
            ok, checks = False, [{"name": "refresh", "passed": False, "detail": f"{type(exc).__name__}: {exc}"[:300], "severity": "error"}]
        if ok:
            shutil.copytree(staging, folder, dirs_exist_ok=True)
            shutil.rmtree(staging)
            self._db(ws).execute("UPDATE dashboards SET status = 'published', last_refresh_at = now(), refresh_count = refresh_count + 1, "
                                 "checks = ? WHERE id = ?", [json.dumps(checks), dashboard_id])
        else:
            shutil.rmtree(staging, ignore_errors=True)
            self._db(ws).execute("UPDATE dashboards SET status = 'stale', checks = ? WHERE id = ?", [json.dumps(checks), dashboard_id])
        self.guard.audit(actor, ws, "dashboard.refresh", dashboard_id, "ok" if ok else "failed")
        if ok and getattr(self, "assets", None):
            self.assets.on_dashboard(actor, ws, dashboard_id, design, checks, refreshed=True, task_id=task_id)
        return {"dashboard_id": dashboard_id, "status": "published" if ok else "stale", "checks": checks}

    def retire(self, actor: Principal, ws: str, dashboard_id: str) -> dict[str, Any]:
        """Stop refreshing and hide a dashboard. Its folder stays (the bundle can still be downloaded); its refresh
        schedule is disabled; a refresh request for it is refused."""
        self.guard.require(actor, ws, "task.control", dashboard_id)
        row = self._db(ws).query("SELECT id, status, schedule_id FROM dashboards WHERE id = ?", [dashboard_id])
        if not row:
            raise KeyError(dashboard_id)
        if row[0]["schedule_id"]:
            self.stores.control.execute("UPDATE schedules SET enabled = false WHERE id = ?", [row[0]["schedule_id"]])
        self._db(ws).execute("UPDATE dashboards SET status = 'retired' WHERE id = ?", [dashboard_id])
        self.guard.audit(actor, ws, "dashboard.retire", dashboard_id, "ok")
        return {"dashboard_id": dashboard_id, "status": "retired"}

    # -- reading ----------------------------------------------------------------------------

    def list(self, actor: Principal, ws: str, *, include_retired: bool = False) -> list[dict[str, Any]]:
        self.guard.require(actor, ws, "workspace.read")
        rows = self._db(ws).query("SELECT id, title, status, created_by, created_at, last_refresh_at, refresh_count, schedule_id, checks "
                                  "FROM dashboards " + ("" if include_retired else "WHERE status <> 'retired' ") + "ORDER BY created_at DESC")
        for r in rows:
            r["checks"] = json.loads(r["checks"]) if r["checks"] else []
        return rows

    def manifest(self, actor: Principal, ws: str, dashboard_id: str) -> dict[str, Any]:
        self.guard.require(actor, ws, "workspace.read", dashboard_id)
        path = self._db(ws).scalar("SELECT path FROM dashboards WHERE id = ?", [dashboard_id])
        if not path:
            raise KeyError(dashboard_id)
        return json.loads((Path(path) / "manifest.json").read_text())

    def extract(self, actor: Principal, ws: str, dashboard_id: str, filename: str) -> bytes:
        self.guard.require(actor, ws, "workspace.read", dashboard_id)
        path = self._db(ws).scalar("SELECT path FROM dashboards WHERE id = ?", [dashboard_id])
        if not path or "/" in filename or not (Path(path) / filename).exists():
            raise KeyError(filename)
        return (Path(path) / filename).read_bytes()

    def bundle(self, actor: Principal, ws: str, dashboard_id: str) -> bytes:
        self.guard.require(actor, ws, "workspace.read", dashboard_id)
        path = self._db(ws).scalar("SELECT path FROM dashboards WHERE id = ?", [dashboard_id])
        if not path:
            raise KeyError(dashboard_id)
        import io  # noqa: PLC0415

        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
            for p in sorted(Path(path).rglob("*")):
                if p.is_file() and ".cache" not in p.parts and "__pycache__" not in p.parts:
                    z.write(p, str(p.relative_to(path)))
        return buf.getvalue()


