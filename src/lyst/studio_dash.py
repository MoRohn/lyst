@callback(Output("ov-findings", "children"), Input(St.STORE, "data"))
def overview_findings(filters: dict):
    """Findings from tested functions: the change, the driving member, the forecast, anomalies."""
    m = S.METRICS[0]
    df = ui.filtered(data.parts(m["name"]), filters)
    w = ui.windows(df)
    out = []
    if w:
        f = ui.fmt(m["format"])
        a, b = df[df["period"] == w[0]], df[df["period"] == w[1]]
        cur, prev = data.value(a, m["name"]), data.value(b, m["name"])
        when = f"in {ui.period_label(w[0])} vs {ui.period_label(w[1])}"
        is_rate = m["format"] == "percent"
        if cur is not None and prev is not None:
            moved = abs(cur - prev) >= (0.001 if is_rate else abs(prev) * 0.005)
            if is_rate:
                d = cur - prev
                good = (d > 0) == m["higher_is_better"]
                out.append(I.Finding("change", f"{m['title']} {'up' if d > 0 else 'down' if d < 0 else 'flat'} {F.pts(abs(d))}" if moved
                                     else f"{m['title']} steady at {f(cur)}",
                                     f"{m['title']} is {f(cur)} {when}, {F.signed(F.pts, d)} from {f(prev)}.",
                                     tone=("good" if good else "bad") if moved else "neutral", magnitude=min(abs(d) * 10, 1.0),
                                     icon="trending_up" if d > 0 else "trending_down"))
            else:
                out.append(I.change(m["title"], cur, prev, f, period=when, higher_is_better=m["higher_is_better"]))
            if moved:
                if m["kind"] == "ratio":
                    out.append(I.rate_driver(drivers.explain_rate(a, b, "num", "den", [S.DIMENSION]), m["title"],
                                             higher_is_better=m["higher_is_better"]))
                else:
                    out.append(I.driver(drivers.explain(a, b, "num", [S.DIMENSION]), m["title"], f, higher_is_better=m["higher_is_better"]))
        y = data.series(df, m["name"]).dropna()
        if len(y) >= 8 and S.GRAIN == "month":
            out.append(I.forecast_note(ts.forecast(y, grain="month"), m["title"], f, stock=is_rate))
        if len(y) >= 25:
            out.append(I.anomaly_note(ts.anomalies(y, period=12), m["title"], f, date_fmt="%b %Y"))
