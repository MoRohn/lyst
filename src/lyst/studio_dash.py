CHECK_SCRIPT = """
import json, sys
sys.path.insert(0, sys.argv[1])
from lystkit.dashkit import checks
rep = checks.check(sys.argv[1], call=True)
print("@@REPORT@@" + json.dumps({"result": rep["result"], "items": rep["items"]}, default=str))
"""


def verify(folder: Path, *, timeout_s: float = 240) -> list[dict[str, Any]]:
    """The kit's in-process check (import, pages, unique ids, URLs, callbacks with their defaults through the
    app's MCP server), run in a separate interpreter on the copy vendored beside the app: Dash keeps process-wide registries and context variables,
    and the engine must not share them with a generated app."""
    import os  # noqa: PLC0415
    import subprocess  # noqa: PLC0415
    import sys  # noqa: PLC0415

    checks: list[dict[str, Any]] = []
    try:
        compile((folder / "app.py").read_text(), str(folder / "app.py"), "exec")
        checks.append({"name": "app_syntax", "passed": True, "detail": "app.py compiles", "severity": "error"})
    except SyntaxError as exc:
        checks.append({"name": "app_syntax", "passed": False, "detail": str(exc), "severity": "error"})
        return checks
    env = {k: v for k, v in os.environ.items() if not k.startswith("LYST_")}
    env.update({"LYSTKIT_MCP_IMAGES": "0", "PYTHONDONTWRITEBYTECODE": "1"})
    try:
        proc = subprocess.run([sys.executable, "-c", CHECK_SCRIPT, str(folder)], capture_output=True, text=True, timeout=timeout_s,
                              cwd=str(folder), env=env)
    except subprocess.TimeoutExpired:
        checks.append({"name": "dash_check", "passed": False, "detail": f"the check did not finish in {timeout_s:.0f}s", "severity": "error"})
        return checks
    line = next((ln for ln in reversed(proc.stdout.splitlines()) if ln.startswith("@@REPORT@@")), None)
    if not line:
        checks.append({"name": "dash_check", "passed": False, "detail": f"check crashed: {(proc.stderr or proc.stdout)[-400:]}",
                       "severity": "error"})
        return checks
    rep = json.loads(line[len("@@REPORT@@"):])
    fails = [i for i in rep["items"] if i["level"] == "FAIL"]
    warns = [i for i in rep["items"] if i["level"] == "WARN"]
    detail = f"{len(rep['items'])} checks" + ("; failed: " + "; ".join(f"{i['check']}: {i['detail'][:160]}" for i in fails) if fails else "")
    checks.append({"name": "dash_check", "passed": rep["result"] == "PASS", "detail": detail, "severity": "error"})
    if warns:
        checks.append({"name": "dash_warnings", "passed": True, "detail": "; ".join(f"{i['check']}: {i['detail'][:120]}" for i in warns),
                       "severity": "warning"})
    return checks


