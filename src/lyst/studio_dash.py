@callback(Output("ov-kpis", "children"), Output("scope-line", "children"), Input(St.STORE, "data"), Input(St.SCHEME, "data"))
def overview_kpis(filters: dict, scheme: str):
    """KPI cards: each metric in the latest period against the one before, with a sparkline."""
    pal = ui.THEME.palette(scheme)
    kpis, sparks = [], []
    scope = ""
    for m in S.METRICS:
        df = ui.filtered(data.parts(m["name"]), filters)
        w = ui.windows(df)
        f = ui.fmt(m["format"])
        if w:
            cur = data.value(df[df["period"] == w[0]], m["name"])
            prev = data.value(df[df["period"] == w[1]], m["name"])
            scope = f"{ui.period_label(w[0])} vs {ui.period_label(w[1])}"
            kpis.append(C.Kpi(m["title"], cur, prev, fmt=f, delta="pts" if m["format"] == "percent" else "pct",
                              higher_is_better=m["higher_is_better"], caption=f"{scope} · {f(prev) if prev is not None else '—'}",
                              info=m["description"] or None))
            s = data.series(df, m["name"]).tail(12)
            sparks.append(Fg.sparkline(list(s.values), pal, kind="line" if m["format"] == "percent" else "area"))
        else:
            kpis.append(C.Kpi(m["title"], data.value(df, m["name"]), fmt=f, delta="none", caption="All periods"))
    active = St.active(filters, ui.FILTERS)
    scope_text = scope + ("" if not active else " · Filtered: " + ", ".join(f"{k} = {v}" for k, v in active.items()))
    return C.kpi_row(kpis, icons=[ICONS.get(m["format"], "sigma") for m in S.METRICS], sparks=sparks or None), scope_text


