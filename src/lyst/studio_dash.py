def _r(s: Any) -> str:
    return repr(s)


def write_app(folder: Path, design: dict[str, Any], manifest: dict[str, Any]) -> list[str]:
    """Write the Dash app files for a design whose extracts are already in folder/data. Returns the file list."""
    from .dashkit import vendor  # noqa: PLC0415

    pkg = folder / "lyst_dash"
    (folder / "pages").mkdir(exist_ok=True)
    (folder / "tests").mkdir(exist_ok=True)
    pkg.mkdir(exist_ok=True)
    n = design.get("narrative") or {}
    dim_label = design["dimension"].replace("_", " ").capitalize()
    title = design["title"]
    description = n.get("subtitle") or f"{', '.join(m['title'] for m in design['metrics'])} by {dim_label.lower()}, on governed metrics"
    metrics = [{"name": m["name"], "title": m["title"], "description": m.get("description") or "", "format": m["format"],
                "higher_is_better": m["higher_is_better"], "kind": m.get("kind", "simple"), "version": m.get("version"),
                "series_sql": m["series_sql"]} for m in design["metrics"]]
    order = n.get("kpi_order")
    if order and set(order) == {m["name"] for m in metrics}:
        metrics.sort(key=lambda m: order.index(m["name"]))
    subs = {"@@TITLE@@": title, "@@DESCRIPTION@@": description.replace('"', "'"), "@@DIM_LABEL@@": dim_label,
            "@@TITLE_R@@": _r(title), "@@DESCRIPTION_R@@": _r(description),
            "@@QUESTION_R@@": _r(n.get("question") or f"What changed in {metrics[0]['title'].lower()}, why, and what is next?"),
            "@@SUBTITLE_R@@": _r(n.get("subtitle") or f"{design['grain'].capitalize()}ly · data through {manifest.get('data_through')}"),
            "@@DIM_R@@": _r(design["dimension"]), "@@DIM_LABEL_R@@": _r(dim_label), "@@GRAIN_R@@": _r(design["grain"]),
            "@@METRICS_R@@": pprint.pformat(metrics, width=110, sort_dicts=False), "@@CREDIT_R@@": _r("Data: Lyst governed metrics. Built by Lyst's Studio."),
            "@@GENERATED_R@@": _r(manifest.get("refreshed_at", ""))}

    def render(tpl: str) -> str:
        out = tpl
        for k, v in subs.items():
            out = out.replace(k, v)
        return out

    files = {
        folder / "app.py": render(APP_PY), folder / "theme.toml": render(THEME_TOML), folder / "requirements.txt": REQUIREMENTS,
        pkg / "__init__.py": '"""Generated by Lyst."""\n', pkg / "settings.py": render(SETTINGS_PY), pkg / "data.py": DATA_PY,
        pkg / "ui.py": UI_PY, folder / "pages" / "overview.py": OVERVIEW_PY, folder / "pages" / "breakdown.py": BREAKDOWN_PY,
        folder / "pages" / "method.py": METHOD_PY, folder / "tests" / "__init__.py": "", folder / "tests" / "test_app.py": TEST_PY,
        folder / "DESIGN.md": design_md(design, manifest, metrics),
    }
    for path, text in files.items():
        path.write_text(text)
    vendored = vendor(folder)
    return sorted([str(p.relative_to(folder)) for p in files] + vendored)


