"""The specialization audit: every profile's example requests, routed and actually run, with what really happened.

For each of the 136 profiles, each example request is (1) routed, to check the profile selects itself, and (2) sent
through the Universal Analyst Core and run to completion by the real runtime on a workspace's data. The outcome is
classified without judgment calls:

- ``answered``: the task finished with a verified answer (outcome ``complete``).
- ``flagged``: an answer was computed but did not pass verification, for instance because it addresses a different
  question than the one asked (outcome ``unverified``).
- ``declined``: Lyst asked for input instead of answering, typically because no approved metric or dataset covers the
  request (outcome ``needs_input``). This is the honest result when the data is not there.
- ``failed``: the task failed.

The audit measures what the system does on the data it is given. It is evidence for maturity, never a substitute for
it: an ``answered`` example shows the pipeline ran and verified, not that the answer is what an expert would give.
"""

from __future__ import annotations

import time
from collections import Counter
from typing import Any

from .catalog import load
from .core import AnalystRequest
from .maturity import assess
from .router import route

OUTCOMES = {"complete": "answered", "unverified": "flagged", "needs_input": "declined"}


def _reason(text: str) -> str:
    t = text.lower()
    if "no approved metric" in t:
        return "no approved metric covers it"
    if "name the dataset" in t:
        return "no dataset named"
    if "causation" in t:
        return "causal claim without a causal design"
    if "matches more than one" in t:
        return "ambiguous metric"
    if "does not address the question" in t:
        return "answer would not address the question"
    return "other"


def run(lyst, actor, workspace_id: str, *, ids: list[str] | None = None) -> dict[str, Any]:
    cat = load()
    rows: list[dict[str, Any]] = []
    t0 = time.perf_counter()
    for pid in ids or list(cat.order):
        p = cat.get(pid)
        for ex in p.quality.example_requests:
            d = route(ex, can=lambda perm: lyst.guard.can(actor, workspace_id, perm))
            selected = [c.id for c in d.selected]
            out = lyst.analyst_core.handle(actor, AnalystRequest(workspace_id=workspace_id, text=ex))
            lyst.runtime.drain()
            t = lyst.runtime.get(actor, out.task_id)
            res = t.get("result") or {}
            answer = res.get("answer") or t.get("error") or ""
            outcome = OUTCOMES.get(t.get("outcome") or "", "failed" if t["status"] == "failed" else "other")
            rows.append({"id": pid, "name": p.name, "domain": p.identity.domain, "level": assess(p)["level"],
                         "example": ex, "routed_to_self": pid in selected, "primary": selected[0] if selected else None,
                         "outcome": outcome, "reason": _reason(answer) if outcome in ("declined", "flagged") else None,
                         "answer": answer[:240]})
    return {"workspace": workspace_id, "catalog_version": cat.version, "seconds": round(time.perf_counter() - t0, 1),
            "rows": rows, "summary": summarize(rows)}


def summarize(rows: list[dict[str, Any]]) -> dict[str, Any]:
    by_role: dict[str, list[dict[str, Any]]] = {}
    for r in rows:
        by_role.setdefault(r["id"], []).append(r)
    verdicts = Counter()
    for rs in by_role.values():
        outs = {r["outcome"] for r in rs}
        verdicts["answers on this data" if "answered" in outs else "flags or declines on this data"] += 1
    return {"examples": len(rows), "roles": len(by_role),
            "routing_self": sum(r["routed_to_self"] for r in rows),
            "outcomes": dict(Counter(r["outcome"] for r in rows)),
            "reasons": dict(Counter(r["reason"] for r in rows if r["reason"])),
            "roles_by_verdict": dict(verdicts)}


def markdown(report: dict[str, Any]) -> str:
    s = report["summary"]
    lines = [
        "# Specialization audit",
        "",
        f"Generated by `scripts/audit_specializations.py` on the `{report['workspace']}` demo workspace plus the synthetic "
        "samples (order events, login events, stores and warehouses, two ledgers, supplier links, customers) "
        f"(catalog {report['catalog_version']}). Every example request of every profile was routed and then run to the end "
        "by the real runtime. Regenerate after changing profiles, methods or data.",
        "",
        "## Summary",
        "",
        f"- Example requests: **{s['examples']}** across **{s['roles']}** profiles.",
        f"- Routed to their own profile: **{s['routing_self']} of {s['examples']}**.",
        "- Outcomes: " + ", ".join(f"{k} **{v}**" for k, v in sorted(s["outcomes"].items())) + ".",
        "- Why requests were declined or flagged: " + ", ".join(f"{k} ({v})" for k, v in sorted(s["reasons"].items(), key=lambda x: -x[1])) + ".",
        "- Profiles: " + ", ".join(f"{k} **{v}**" for k, v in s["roles_by_verdict"].items()) + ".",
        "",
        "Reading it: *answered* means the pipeline produced a verified answer on this data (finance and support metrics "
        "plus the samples). *Declined* is the correct, honest behaviour when the workspace has no data for the discipline. "
        "*Flagged* means an answer was computed but not presented as verified, usually because it would not address "
        "the question.",
        "",
        "## Per example",
        "",
        "| Profile | Level | Example | Routed | Outcome | Reason |",
        "|---|---|---|---|---|---|",
    ]
    for r in report["rows"]:
        ex = r["example"].replace("|", "/")
        lines.append(f"| {r['name']} | {r['level']} | {ex} | {'yes' if r['routed_to_self'] else 'no: ' + str(r['primary'])} | "
                     f"{r['outcome']} | {r['reason'] or ''} |")
    return "\n".join(lines) + "\n"
